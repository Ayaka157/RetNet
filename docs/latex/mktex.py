CODE_LANG = {
    "python": "Python",
    "powershell": "PowerShell",
    "text": "",
    "bash": "bash",
    "json": "JSON",
    "": "",
}


def collect_blocks(lines: list[str]):
    """Yield (kind, payload) blocks from Markdown lines."""
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]

        # fenced code
        if line.lstrip().startswith("```"):
            lang = line.lstrip()[3:].strip()
            body: list[str] = []
            i += 1
            while i < n and not lines[i].lstrip().startswith("```"):
                body.append(lines[i])
                i += 1
            i += 1  # closing fence
            yield ("code", (lang, body))
            continue

        # display math
        if line.strip() == "$$":
            body = []
            i += 1
            while i < n and lines[i].strip() != "$$":
                body.append(lines[i])
                i += 1
            i += 1
            yield ("math", body)
            continue

        # horizontal rule
        if line.strip() in ("---", "***", "___"):
            i += 1
            yield ("rule", None)
            continue

        # heading
        m = re.match(r"^(#{1,6})\s+(.*)$", line)
        if m:
            i += 1
            yield ("head", (len(m.group(1)), m.group(2).strip()))
            continue

        # blockquote
        if line.lstrip().startswith(">"):
            body = []
            while i < n and lines[i].lstrip().startswith(">"):
                body.append(re.sub(r"^\s*>\s?", "", lines[i]))
                i += 1
            yield ("quote", body)
            continue

        # table (header row followed by a separator row)
        if "|" in line and i + 1 < n and re.match(
            r"^\s*\|?[\s:|-]+\|[\s:|-]*$", lines[i + 1]
        ):
            body = []
            while i < n and "|" in lines[i] and lines[i].strip():
                body.append(lines[i])
                i += 1
            yield ("table", body)
            continue

        # list
        if re.match(r"^\s*(?:[-*+]|\d+\.)\s+", line):
            body = []
            while i < n and (
                re.match(r"^\s*(?:[-*+]|\d+\.)\s+", lines[i])
                or (lines[i].strip() and lines[i].startswith("   ") and body)
            ):
                if re.match(r"^\s*(?:[-*+]|\d+\.)\s+", lines[i]) or lines[i].strip():
                    body.append(lines[i])
                i += 1
            yield ("list", body)
            continue

        # blank
        if not line.strip():
            i += 1
            yield ("blank", None)
            continue

        # paragraph: accumulate until a blank line or a block starter.  A
        # nested heading does NOT break a paragraph: it is returned to
        # render_blocks, which splits on it, so subsections are kept inside
        # their parent section.
        body = []
        while i < n and lines[i].strip():
            if re.match(r"^#{1,6}\s+", lines[i]):
                break
            if lines[i].lstrip().startswith("```") or lines[i].strip() == "$$":
                break
            if lines[i].lstrip().startswith(">"):
                break
            if re.match(r"^\s*(?:[-*+]|\d+\.)\s+", lines[i]):
                break
            body.append(lines[i])
            i += 1
        if not body:  # safety valve
            body.append(lines[i])
            i += 1
        yield ("para", body)


def render_table(rows: list[str], labels, caption: str | None = None) -> str:
    """Render a Markdown table, optionally with a numbered caption above it."""
    def cells(r: str) -> list[str]:
        r = r.strip()
        if r.startswith("|"):
            r = r[1:]
        if r.endswith("|"):
            r = r[:-1]
        return [c.strip() for c in r.split("|")]

    header = cells(rows[0])
    body = [cells(r) for r in rows[2:]]
    ncol = len(header)

    # column count sanity: pad short rows
    for r in body:
        while len(r) < ncol:
            r.append("")

    # Estimate each column's natural width in points so that a dense table can
    # be given explicit p{} widths instead of running past the right margin.
    # The text block is 164 mm wide at \small (see the geometry setup); a Latin
    # glyph averages ~4.5 pt and a CJK glyph ~10 pt at this size.
    TEXTWIDTH = 465.0        # pt, \textwidth
    TABCOLSEP = 5.0          # pt, matches \setlength{\tabcolsep}{5pt}
    MONO = 4.6               # pt per monospace glyph at \small
    # \tabcolsep sits on both sides of every column, so the usable width for
    # the p{} columns themselves is smaller than \textwidth.
    AVAIL = TEXTWIDTH - 2.0 * TABCOLSEP * ncol

    def cell_widths(c: str) -> tuple[float, float]:
        """(natural width, widest guaranteed-unbreakable segment) of a cell.

        A code span longer than the `add_breaks` threshold may break before
        `/ _ . -`, so its floor is the widest such segment; a shorter span
        stays glued together.  Chinese prose wraps between any two characters.
        The natural width decides whether the table needs explicit column
        widths at all.

        With `compact_tables` the longest whitespace-free run of ordinary text
        is also treated as a floor: a bold nine-digit number cannot be broken,
        so a column squeezed below it is an Overfull hbox by construction.
        """
        total = 0.0
        widest = 0.0
        i = 0
        n = len(c)
        while i < n:
            if c[i] == "`":
                j = c.find("`", i + 1)
                if j < 0:
                    j = n
                span = c[i + 1:j]
                total += MONO * len(span)
                if len(span) > 18 or COMPACT_TABLES:
                    floors = [MONO * len(p) for p in code_segments(span)]
                    widest = max(widest, max(floors) if floors else MONO)
                else:
                    widest = max(widest, MONO * len(span))
                i = j + 1
                continue
            ch = c[i]
            if CJK_RE.match(ch):
                total += 10.0
                widest = max(widest, 10.0)
            else:
                total += 4.5
                if COMPACT_TABLES and not ch.isspace():
                    # length of the whitespace-free run starting here
                    run = 0
                    while i + run < n and not c[i + run].isspace():
                        run += 1
                    widest = max(widest, 4.9 * run)
            i += 1
        return total, widest

    naturals = []
    naturals_floors = []
    for j in range(ncol):
        cells_j = [header[j]] + [r[j] for r in body if j < len(r)]
        best_natural = 0.0
        best_unbreakable = 0.0
        for c in cells_j:
            nat, unbr = cell_widths(c)
            best_natural = max(best_natural, nat)
            best_unbreakable = max(best_unbreakable, unbr)
        naturals.append(best_natural + 12.0)
        # A column cannot usefully be narrower than its widest unbreakable
        # unit, so that is its floor.
        naturals_floors.append(min(best_unbreakable + 12.0, AVAIL / max(ncol - 1, 1)))

    total = sum(naturals)
    if total > AVAIL:
        # Shrink proportionally, but never below the widest unbreakable unit
        # of the column: a column narrower than its content cannot wrap it,
        # it only forces an Overfull box.
        floors = naturals_floors
        scale = AVAIL / total
        widths = [max(w * scale, f) for w, f in zip(naturals, floors)]
        over = sum(widths) - AVAIL
        if over > 0:
            # Take the excess back from the columns that have the most slack
            # above their floor, plus a proportional bite out of the rest.
            slack = [w - f for w, f in zip(widths, floors)]
            tot_slack = sum(slack)
            if tot_slack > 0:
                take = min(over, tot_slack)
                widths = [w - take * s / tot_slack for w, s in zip(widths, slack)]
                over = sum(widths) - AVAIL
            if over > 0:
                # Everything is already at its floor; scale the floors.
                k = AVAIL / sum(widths)
                widths = [w * k for w in widths]

        spec_parts = []
        for j, w in enumerate(widths):
            spec_parts.append(
                r">{\RaggedRight\arraybackslash}p{" + f"{w:.1f}pt" + "}"
            )
        # A table with many columns cannot hold its cells at \small: the widths
        # above are scaled to \textwidth, and a five-digit bold header needs
        # more room than a 20 pt column has.  Rendering such a table one size
        # down leaves the widths (computed for \small) as generous slack.
        tablefont = r"\scriptsize" if (COMPACT_TABLES and ncol >= 10) else r"\small"
        header_line = " & ".join(
            r"\textbf{" + inline(c, labels) + "}" for c in header) + r" \\"
        row_lines = [" & ".join(inline(c, labels) for c in r) + r" \\"
                     for r in body]
        if COMPACT_TABLES and not caption and len(body) >= LONG_TABLE_ROWS:
            # Taller than a page: an unbreakable `tabular` would be shipped past
            # the paper edge, so let it break -- the header and the bottom rule
            # repeat on every page it spans.
            return "\n".join([
                "{\\" + tablefont.lstrip("\\"),
                r"\setlength{\arraystretch}{1.05}",
                r"\begin{longtable}{" + "".join(spec_parts) + "}",
                r"\toprule",
                header_line,
                r"\midrule",
                r"\endhead",
                r"\bottomrule",
                r"\endfoot",
            ] + row_lines + [r"\end{longtable}", "}"])
        lines = [r"\begin{center}", tablefont]
        if caption:
            lines.append(r"\captionof{table}{" + inline(caption, labels) + "}")
        lines += [
            r"\begin{tabular}{" + "".join(spec_parts) + "}",
            r"\toprule",
            header_line,
            r"\midrule",
        ]
        lines += row_lines
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{center}"]
        return "\n".join(lines)

    spec = "l" + "r" * (ncol - 1)
    lines = [r"\begin{center}", r"\small"]
    if caption:
        lines.append(r"\captionof{table}{" + inline(caption, labels) + "}")
    lines += [
        r"\begin{tabular}{" + spec + "}",
        r"\toprule",
        " & ".join(r"\textbf{" + inline(c, labels) + "}" for c in header) + r" \\",
        r"\midrule",
    ]
    for r in body:
        lines.append(" & ".join(inline(c, labels) for c in r) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{center}"]
    return "\n".join(lines)


def render_list(items: list[str], labels) -> str:
    """Render a flat/nested Markdown list as nested LaTeX lists."""
    entries: list[tuple[int, str, bool]] = []
    for raw in items:
        m = re.match(r"^(\s*)([-*+]|\d+\.)\s+(.*)$", raw)
        if m:
            indent = len(m.group(1))
            ordered = m.group(2)[0].isdigit()
            entries.append((indent, m.group(3).strip(), ordered))
        elif entries:
            indent, text, ordered = entries[-1]
            entries[-1] = (indent, text + " " + raw.strip(), ordered)

    out: list[str] = []
    stack: list[tuple[int, bool]] = []

    def close_to(depth: int):
        while len(stack) > depth:
            _, was_ordered = stack.pop()
            out.append(r"\end{enumerate}" if was_ordered else r"\end{itemize}")

    def open_new(depth: int, ordered: bool):
        out.append(r"\begin{enumerate}" if ordered else r"\begin{itemize}")
        stack.append((depth, ordered))

    for indent, text, ordered in entries:
        depth = len(stack)
        if depth and indent > stack[-1][0]:
            open_new(indent, ordered)
        else:
            close_to(1 if indent > 0 else 0)
            while stack and indent < stack[-1][0]:
                close_to(len(stack) - 1)
            if not stack:
                open_new(indent, ordered)
        out.append(r"  \item " + inline(text, labels))
    close_to(0)
    return "\n".join(out)


def render_blocks(lines: list[str], labels, is_en: bool = False,
                  caption_hints: Sequence | None = None) -> str:
    """Render Markdown lines, keeping nested subsections inside their parent.

    `collect_blocks` yields every heading as its own block, so a level-4
    heading would otherwise be emitted as a sibling of the level-3 heading it
    belongs to.  This walks the block stream and groups each heading with
    everything that follows it at a deeper level, then recurses.

    Language selection happens earlier, in `split_by_language`, so by the time
    a section reaches this function it is already single-language.
    """
    blocks = [b for b in collect_blocks(lines) if b[0] != "blank"]

    def level_of(block) -> int | None:
        return block[1][0] if block[0] == "head" else None

    def render_seq(seq: list, min_level: int) -> list[str]:
        out: list[str] = []
        i = 0
        n = len(seq)
        while i < n:
            kind, payload = seq[i]
            lvl = level_of(seq[i])
            if lvl is None:
                body = render_one(kind, payload)
                if body:
                    out.append(body)
                i += 1
                continue

            # heading: absorb every following block up to the next heading
            # whose level is <= this one.
            j = i + 1
            while j < n:
                nl = level_of(seq[j])
                if nl is not None and nl <= lvl:
                    break
                j += 1
            child = seq[i + 1:j]
            body = render_one(*seq[i])
            deep = render_seq(child, lvl + 1) if child else []
            if body:
                out.append(body)
            out.extend(deep)
            i = j
        return out

    def render_one(kind, payload) -> str:
        if kind == "rule":
            return r"\reportrule"
        if kind == "head":
            level, text = payload
            text = strip_number(text)
            # `### 1.2 English` names the language of the text that follows,
            # not a topic; the heading itself is dropped but the text is kept.
            # Test the raw title -- en_clean_heading() already blanks a marker,
            # so it must not be consulted here or this never fires.
            if is_language_marker(text):
                return ""
            if level <= 3:
                cmd = "subsection" if level == 3 else "section"
                return "\\" + cmd + "{" + inline(text, labels) + "}"
            if level == 4:
                return r"\subsubsection{" + inline(text, labels) + "}"
            return r"\paragraph{" + inline(text, labels) + "}"
        if kind == "para":
            text = " ".join(p.strip() for p in payload)
            if CAPTIONS_IN_SOURCE:
                m = SOURCE_CAPTION_RE.match(text)
                if m:
                    # the source's own caption line: set the label bold and keep
                    # the rest as normal text, exactly where the source put it
                    return (r"\noindent\textbf{" + inline(m.group(1), labels)
                            + ".}" + (" " + inline(m.group(2), labels)
                                      if m.group(2) else ""))
            return inline(text, labels)
        if kind == "quote":
            return (
                "\\begin{notebox}\n"
                + render_blocks(payload, labels, is_en, caption_hints)
                + "\n\\end{notebox}"
            )
        if kind == "table":
            return render_table(
                payload, labels, infer_caption(payload, is_en, caption_hints))
        if kind == "list":
            return render_list(payload, labels)
        if kind == "math":
            return "\\[\n" + norm_math("\n".join(payload)) + "\n\\]"
        if kind == "code":
            lang, body = payload
            lst = CODE_LANG.get(lang.lower(), "")
            opt = r"language=" + lst if lst else ""
            return (
                "\\begin{lstlisting}[" + opt + "]\n"
                + "\n".join(body)
                + "\n\\end{lstlisting}"
            )
        return ""

    return "\n\n".join(x for x in render_seq(blocks, 1) if x.strip())


def split_by_language(lines: list[str]) -> dict[str, list[str]]:
    """Split a section's Markdown into its Chinese and English halves.

    The source marks the halves with subsections such as `### 1.1 中文` and
    `### 1.2 English`.  Splitting the *Markdown* is much more robust than
    splitting the rendered LaTeX afterwards: the marker headings survive here,
    whereas the renderer deletes them, leaving the two halves glued together
    with nothing to tell them apart.

    Text before the first marker is assigned by its own script.  A section with
    no markers at all (the reference list) is returned under both keys, so
    callers can index the result unconditionally.
    """
    marker_at: list[tuple[int, bool]] = []  # (line index, is_english)
    for i, line in enumerate(lines):
        m = re.match(r"^#{3,6}\s+(.*)$", line)
        if m and is_language_marker(strip_number(m.group(1))):
            marker_at.append((i, "English" in m.group(1)))

    if not marker_at:
        return {"zh": list(lines), "en": list(lines)}

    result: dict[str, list[str]] = {"zh": [], "en": []}
    first_marker = marker_at[0][0]
    preamble = lines[:first_marker]
    # the preamble belongs to whichever language it is written in
    (result["en"] if cjk_count("\n".join(preamble)) < 10 else result["zh"]).extend(
        preamble
    )

    bounds = [idx for idx, _ in marker_at] + [len(lines)]
    for k, (idx, is_en) in enumerate(marker_at):
        chunk = lines[idx + 1:bounds[k + 1]]
        result["en" if is_en else "zh"].extend([""] + chunk)
    return result


def strip_number(text: str) -> str:
    """Remove a leading Markdown section number such as '3.4.1 '."""
    return re.sub(r"^\d+(?:\.\d+)*\.?\s+", "", text).strip()


