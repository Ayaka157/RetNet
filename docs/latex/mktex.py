def caption_supplement_tables(text: str,
                              headers: Mapping[str, str] | None = None) -> str:
    """Add a numbered caption to each table in the English supplement.

    The supplement writes tables as `\\begin{center}\\small` followed by a
    `tabular`, so the caption is slipped in between the two.  The table's
    header row selects the caption; each header key is consumed on use, which
    keeps a distinctive header from being stolen by an earlier table that also
    contains it as a substring.  `headers` defaults to the 272M table map; a
    different report passes its own (see `SUPPLEMENT_TABLE_HEADERS_05B`).
    """
    lines = text.splitlines()
    remaining = dict(SUPPLEMENT_TABLE_HEADERS if headers is None else headers)
    out: list[str] = []
    for i, line in enumerate(lines):
        out.append(line)
        stripped = line.strip()
        if stripped not in (r"\begin{center}", r"\begin{center}\small"):
            continue
        if any("captionof" in l for l in out[-3:]):
            continue
        # the tabular must start on this line or the next
        if "tabular" not in stripped and "tabular" not in lines[i + 1]:
            continue
        # the header row is the first content line that is not a rule or a
        # table-setup command (`\setlength`, `\small`, ...)
        header = ""
        for l in lines[i + 1:i + 12]:
            s = l.strip()
            if not s or s.startswith("\\begin{tabular"):
                continue
            if s in (r"\toprule", r"\midrule", r"\small") or s.startswith(r"\setlength"):
                continue
            header = s
            break
        # prefer the longest available key that the header starts with
        best = None
        for prefix in remaining:
            if header.startswith(prefix):
                if best is None or len(prefix) > len(best):
                    best = prefix
        if best is None:
            continue
        cap = remaining.pop(best)
        if stripped == r"\begin{center}":
            out.append(r"\small")
        out.append(r"\captionof{table}{" + cap + "}")
    return "\n".join(out)


