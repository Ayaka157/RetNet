# A rendered subsection boundary, e.g. `\subsection{4.4 English (condensed)}`.
SUBHEAD_RE = re.compile(r"\\(sub)*section\*?\{")

CJK_RE = re.compile(r"[\u4e00-\u9fff]")


def heading_of(chunk: str) -> str:
    """The title of the first heading in a rendered LaTeX chunk."""
    m = SUBHEAD_RE.search(chunk)
    if not m:
        return ""
    end = chunk.find("}", m.end())
    return chunk[m.end():end] if end > 0 else ""


def filter_lang(body: str, want_english: bool) -> str:
    """Keep only the parts of a rendered section written in one language.

    The source splits a bilingual section with `### 1.1 中文` and
    `### 1.2 English`.  Those marker headings have already been removed by the
    renderer, so the text that followed each marker became the preamble of the
    *next* segment.  A segment is therefore classified by the marker that
    introduced it; the first segment has no marker and is classified by its own
    text.  Sections with no markers at all (the reference list) are handed to
    the edition that asked for them whole.
    """
    parts: list[str] = []
    pos = 0
    for m in SUBHEAD_RE.finditer(body):
        parts.append(body[pos:m.start()])
        pos = m.start()
    parts.append(body[pos:])

    intro, subs = parts[0], parts[1:]

    has_marker = any(is_language_marker(heading_of(s)) for s in subs)
    has_cjk_sub = any(
        cjk_count(heading_of(s)) >= 10 or cjk_count(s) >= 40 for s in subs
    )
    has_latin_sub = any(
        "English" in heading_of(s) for s in subs
    ) or any(
        heading_of(s).strip() == "" and cjk_count(s) < 40 for s in subs
    )
    # A preamble is ambiguous only when the section really is bilingual.  For
    # a single-language section (the reference list, whose Chinese note carries
    # its own \subsection* heading) the text must be kept as it stands.
    mixed = has_marker and has_cjk_sub and has_latin_sub

    kept: list[str] = []
    intro_is_en = cjk_count(intro) < 10
    if not mixed:
        if intro.strip():
            kept.append(intro)
    elif intro_is_en == want_english and intro.strip():
        kept.append(intro)

    pending_en: bool | None = None
    for sub in subs:
        head = heading_of(sub)
        if is_language_marker(head):
            pending_en = "English" in head
            if pending_en == want_english:
                kept.append(sub)
            continue
        if head == "":  # text that followed a dropped marker heading
            if pending_en is None:
                is_en = cjk_count(sub) < 10
            else:
                is_en = pending_en
            if is_en == want_english:
                kept.append(sub)
            continue
        # a real subsection heading: classify by its own text
        if want_english and cjk_count(head) >= 10:
            continue
        if not want_english and "English" in head:
            continue
        kept.append(sub)
    return "\n\n".join(k for k in kept if k.strip())


def is_language_marker(head: str) -> bool:
    """True for a heading that names a language rather than a topic."""
    return head.strip() in ("中文", "English", "English (condensed)")


def is_english(title: str) -> bool:
    """True for the top-level sections marked English in the source."""
