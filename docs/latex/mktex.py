REPORTS = {r.key: r for r in (R_272M, R_05B, R_SELFTEST)}


def build(keys: Sequence[str] | None = None, strict: bool = False) -> int:
    """Build the requested reports; default: every available default report.

    A report whose source or supplement is missing is skipped with a notice --
    except when it was asked for by name, which is an error.
    """
    requested = [k for k, r in REPORTS.items() if r.default] if keys is None \
        else list(keys)
    built = 0
    for key in requested:
        report = REPORTS.get(key)
        if report is None:
            raise SystemExit(
                f"unknown report {key!r}; known: {', '.join(REPORTS)}")
        missing = [p for p in (report.src, report.supplement)
                   if p is not None and not p.exists()]
        if missing:
            def _rel(p: Path) -> str:
                try:
                    return str(p.relative_to(ROOT))
                except ValueError:
                    return str(p)
            msg = (f"[skip] {report.key} ({report.label}): not available yet: "
                   + ", ".join(_rel(m) for m in missing))
            if strict or keys is not None:
                raise SystemExit(msg)
            print(msg)
            continue
        build_report(report)
        built += 1
    if built == 0:
        print("nothing to build")
    return built


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Markdown -> XeLaTeX sources for the RetNet reports")
    parser.add_argument("--report", action="append", metavar="KEY",
                        help="build only this report (repeatable)")
    parser.add_argument("--list", action="store_true",
                        help="list the configured reports and their sources")
    args = parser.parse_args(argv)
    if args.list:
        for report in REPORTS.values():
            state = "available" if report.src.exists() else "source missing"
            print(f"{report.key:9} {report.label:16} {state:15} {report.src}")
        return 0
    build(args.report, strict=bool(args.report))
    return 0


