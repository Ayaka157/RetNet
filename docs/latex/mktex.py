@dataclass(frozen=True)
class Report:
    """Everything the build needs to know about one pair of editions."""

    key: str
    label: str
    src: Path
    zh_name: str
    en_name: str
    # included in a bare `python mktex.py` run
    default: bool = True
    zh_dir: Path = ROOT / "zh"
    en_dir: Path = ROOT / "en"
    zh_preamble: Path = ROOT / "zh" / "_preamble.tex"
    zh_titles: Path = ROOT / "zh" / "_titles.tex"
    en_preamble: Path = ROOT / "en" / "_preamble.tex"
    en_titles: Path = ROOT / "en" / "_titles.tex"
    # `../figures/` when the generated .tex lives in `docs/latex/<lang>/`
    figure_prefix: str = "../figures/"

    # ---- Chinese edition -------------------------------------------------
    # "bilingual": keep the Chinese half of every `### N.N 中文`/`English` pair.
    # "mono": the Markdown body *is* the Chinese text; do not split anything.
    split_mode: str = "bilingual"
    zh_skip_sections: tuple[str, ...] = ()    # typeset on the cover instead
    zh_front_matter: tuple[str, ...] = ()     # rendered before the contents
    zh_front_matter_tail: str = ""            # the TOC block, if front matter is used
    zh_refs_prefix: str = "参考文献"
    caption_hints: Sequence = ()              # Markdown table -> caption map
    # the Markdown writes its own `表 N.` caption lines, so do not generate them
    captions_in_source: bool = False
    # Opt in to the table-fitting fixes: break separator-free code runs (long
    # hashes, base64), offer breaks inside *every* code span, and set a table
    # with ten or more columns one size down.  Off by default because turning it
    # on rewrites the already-delivered 272M sources.
    compact_tables: bool = False

    # ---- English edition -------------------------------------------------
    en_sections_from_source: frozenset[str] = frozenset()
    en_references_from_source: bool = False
    en_title_map: Mapping[str, str] = field(default_factory=dict)
    supplement: Path | None = None
    supplement_ref_note: str | None = None
    supplement_appendix_anchor: str | None = None
    supplement_table_headers: Mapping[str, str] = field(default_factory=dict)
    # give long `\code{}` spans in the supplement break points (Overfull fix)
    break_supplement_code: bool = False
    figures_en: Sequence = ()
    figures_zh: Sequence = ()


def source_key(clean_title: str) -> str:
    """The Chinese half of a bilingual section title."""
    head = clean_title.split(" / ")[0]
    return strip_number(head).strip()


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def build_zh(report: Report, chunks, labels) -> Path:
    """Write the Chinese edition of one report; return the .tex path."""
    report.zh_dir.mkdir(parents=True, exist_ok=True)
    tex = [read(report.zh_preamble), read(report.zh_titles)]
    front: list[str] = []
    body: list[str] = []
    appendix_started = False

    # Every top-level section is kept.  In "bilingual" mode its
    # `### N.N English` subsections are dropped (this PDF is the Chinese
    # edition); in "mono" mode the Markdown body is already Chinese-only and is
    # rendered as it stands.
    for title, sec in chunks:
        clean = strip_number(title)
        if clean in report.zh_skip_sections:
            # Abstracts and the English subtitle are typeset on the cover.
            continue
        zh_lines = sec if report.split_mode == "mono" \
            else split_by_language(sec)["zh"]
        rendered = render_blocks(zh_lines, labels, is_en=False,
                                 caption_hints=(
                                     () if report.captions_in_source
                                     else report.caption_hints))
        rendered = inject_figures(rendered, is_en=False,
                                  figures_zh=report.figures_zh,
                                  prefix=report.figure_prefix)
        if not rendered.strip():
            continue
        if clean in report.zh_front_matter:
            # The abstract is taken from the Markdown so that it cannot drift
            # from the source; it is listed in the contents but not numbered.
            front.append(r"\section*{" + inline(clean, labels) + "}")
            front.append(r"\addcontentsline{toc}{section}{"
                         + inline(clean, labels) + "}")
            front.append(rendered)
            continue
        if clean.startswith(report.zh_refs_prefix):
            body.append(r"\backmattersection{参考文献}\label{sec:refs}")
        else:
            name = zh_heading(clean)
            if name.startswith("附录") and not appendix_started:
                body.append(r"\startappendix")
                appendix_started = True
            body.append(r"\section{" + inline(name, labels) + "}")
        body.append(rendered)

    if report.zh_front_matter and not front:
        print(f"WARNING: {report.key}: none of {report.zh_front_matter} found in "
              f"{report.src.name}; the front matter is empty", file=sys.stderr)
    tex.extend(front)
    if report.zh_front_matter_tail:
        tex.append(report.zh_front_matter_tail)
    tex.extend(body)
    tex.append(r"\end{document}")
    out = report.zh_dir / (report.zh_name + ".tex")
    out.write_text("\n\n".join(tex) + "\n", encoding="utf-8")
    return out


def build_en(report: Report, chunks, labels) -> Path:
    """Write the English edition of one report; return the .tex path."""
    report.en_dir.mkdir(parents=True, exist_ok=True)
    tex = [read(report.en_preamble), read(report.en_titles)]
    refs_body = None

    # The English edition is a coherent English report: the sections listed in
    # `en_sections_from_source` come from the source's own English prose (for
    # 272M that is the Introduction, whose `### 1.2 English` half is complete),
    # and everything else is supplied by the hand-written supplement.
    # Rendering the source's condensed `### N.N English` abstracts *as well*
    # would duplicate the supplement.
    for title, sec in chunks:
        clean = strip_number(title)
        if clean.startswith(report.zh_refs_prefix):
            refs_body = sec
            continue
        if source_key(clean) not in report.en_sections_from_source:
            continue
        rendered = render_blocks(split_by_language(sec)["en"], labels, is_en=True,
                                 caption_hints=report.caption_hints)
        if not rendered.strip():
            continue
        tex.append(r"\section{"
                   + inline(en_heading(clean, report.en_title_map), labels)
                   + "}")
        tex.append(rendered)

    if report.supplement is not None:
        # The supplement carries the rest of the report (for 0.5B: all of it)
        # and goes before the bibliography.  Its figures are injected at the
        # subsections that discuss them, and its appendices switch the section
        # counter to letters.
        supplement = merge_supplement(report.supplement)
        supplement = caption_supplement_tables(
            supplement, report.supplement_table_headers)
        if report.break_supplement_code:
            supplement = breakable_supplement_code(supplement)
        supplement = inject_figures(supplement, is_en=True,
                                    figures=report.figures_en,
                                    figures_zh=report.figures_zh,
                                    prefix=report.figure_prefix)
        if report.supplement_ref_note:
            # The supplement ends with its own reference-reliability note, but
            # for 272M the note is authored here (render_references) so that it
            # and the bibliography are numbered as back matter rather than as
            # two more appendices.  Drop the supplement's copy.
            supplement = re.split(
                r"\\section\*?\{" + report.supplement_ref_note + r"\}",
                supplement)[0].rstrip()
        if report.supplement_appendix_anchor:
            supplement = supplement.replace(
                report.supplement_appendix_anchor,
                "\\startappendix\n" + report.supplement_appendix_anchor,
                1,
            )
        tex.append(supplement)

    if report.en_references_from_source:
        # the bibliography is back matter: numbered afresh, not an appendix
        tex.append(r"\backmattersection{References}\label{sec:refs}")
        if refs_body is not None:
            tex.append(render_references(refs_body, labels))
    tex.append(r"\end{document}")
    out = report.en_dir / (report.en_name + ".tex")
    out.write_text("\n\n".join(tex) + "\n", encoding="utf-8")
    return out


def build_report(report: Report) -> None:
    """Build both editions of one report."""
    raw = report.src.read_text(encoding="utf-8", errors="replace")
    lines = raw.splitlines()

    # ---- preamble / abstract area (before the first '## ' heading) -------
    # The cover, abstract and contents are hand-written fragments; the Markdown
    # text above the first '## ' heading is only used to find that boundary.
    first = next(i for i, l in enumerate(lines) if SEC_RE.match(l))

    chunks = split_sections(lines[first:])
    labels = {"参考文献--references": "sec:refs"}

    with table_fitting(report.compact_tables), \
            captions_from_source(report.captions_in_source):
        zh_tex = build_zh(report, chunks, labels)
        en_tex = build_en(report, chunks, labels)

    print(f"[{report.key}] {len(chunks)} sections -> {zh_tex.name}, {en_tex.name}")
    print(f"[{report.key}] zh sections:",
          [strip_number(t) for t, _ in chunks])
    print(f"[{report.key}] en supplement:",
          report.supplement.name if report.supplement else "(none)")


