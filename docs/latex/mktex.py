SEC_RE = re.compile(r"^##\s+(.*)$")


def split_sections(lines: list[str]):
    """Split the document body into (title, lines) chunks at level-2 headings."""
    chunks: list[tuple[str, list[str]]] = []
    cur_title = None
    cur: list[str] = []
    for line in lines:
        m = SEC_RE.match(line)
        if m:
            if cur_title is not None:
                chunks.append((cur_title, cur))
            cur_title = m.group(1).strip()
            cur = []
        else:
            if cur_title is None:
                continue
            cur.append(line)
    if cur_title is not None:
        chunks.append((cur_title, cur))
    return chunks


