# A backslash that begins a control sequence (\code, \_ , \%) is generated by
# this converter or comes from a heading map, so it must be passed through;
# any other backslash is literal source text and has to be escaped.
CTRLSEQ_RE = re.compile(r"\\(?=[A-Za-z_]|\s|$)")

# A `\\code{}` span longer than this gets an explicit break opportunity every
# this many characters; without it such a run is an Overfull hbox in any column
# narrower than the run itself.
CODE_BREAK_RUN = 12

# A Markdown table with at least this many body rows is taller than a page at
# \small, so it is rendered as a breakable `longtable` (see render_table).
LONG_TABLE_ROWS = 18

# Table-fitting fixes are **opt-in per report**.  The 272M editions are already
# delivered and byte-stable, and their Chinese text does contain one such run,
# so turning the fixes on globally would rewrite an accepted artefact.  A report
# sets `Report.compact_tables` and `build_report` switches this for its build.
COMPACT_TABLES = False


@contextmanager
def table_fitting(enabled: bool):
    """Turn the table-fitting fixes on for the duration of one build."""
    global COMPACT_TABLES
    previous = COMPACT_TABLES
    COMPACT_TABLES = enabled
    try:
        yield
    finally:
        COMPACT_TABLES = previous


# Some reports write their own captions into the Markdown as standalone
# `表 N. ...` / `图 N. ...` lines, already numbered and continuous.  Generating a
# caption as well would print two captions above every table -- and when one
# table's map entry is missing, the generated counter silently shifts every
# later number.  In this mode the source line *is* the caption: it is set as a
# bold label plus normal text, and no `\captionof` is emitted.
CAPTIONS_IN_SOURCE = False


@contextmanager
def captions_from_source(enabled: bool):
    """Use the Markdown's own `表 N.` lines as captions for the whole build."""
    global CAPTIONS_IN_SOURCE
    previous = CAPTIONS_IN_SOURCE
    CAPTIONS_IN_SOURCE = enabled
    try:
        yield
    finally:
        CAPTIONS_IN_SOURCE = previous


# a source caption line: `表 21. ...`, `图 3、...`, `表2.` ...
SOURCE_CAPTION_RE = re.compile(r"^((?:表|图)\s*\d+)\s*[.、]\s*(.*)$")


def add_breaks(s: str) -> str:
    """Insert break opportunities into an escaped code span.

    Input is the output of `escape_code`: it contains whole macros such as
    `\\textbackslash{}` and `\\%`.  Breaks are placed before the usual code
    separators and before each macro, never inside one -- splitting
    `\\textbackslash{}` would corrupt it.

    A run of alphanumerics with no separator at all (a 64-character sha256, a
    base64 blob) has no break opportunity of its own and therefore cannot be
    wrapped in a narrow table column: it is an Overfull hbox by construction.
    Such a run is broken every `CODE_BREAK_RUN` characters.  `\\allowbreak`
    only *permits* a break, so ordinary code spans are unaffected.

    Deliberately *not* a break after every character: a code span may contain
    text such as `$\\times$`, and splitting that would hand TeX a stray `\\t`,
    which is a math-accent error.
    """
    out: list[str] = []
    in_math = False
    run = 0
    i = 0
    n = len(s)
    while i < n:
        # never break inside `$...$`: a break there would land in math mode
        if s[i] == "$":
            in_math = not in_math
            out.append(s[i])
            i += 1
            continue
        if in_math:
            out.append(s[i])
            i += 1
            continue
        # an escaped-character macro such as \_ or \textbackslash{} moves as a
        # unit, and a break may be offered before it
        if s[i] == "\\" and i + 1 < n:
            j = i + 1
            if s[j].isalpha():
                while j < n and s[j].isalpha():
                    j += 1
                if j < n and s[j] == "{":
                    k = s.find("}", j)
                    j = k + 1 if k > 0 else n
            else:
                j += 1
            out.append(r"\allowbreak{}" + s[i:j])
            i = j
            run = 0
            continue
        if s[i] in ".-/":
            out.append(r"\allowbreak{}")
            run = 0
        elif COMPACT_TABLES and run >= CODE_BREAK_RUN:
            out.append(r"\allowbreak{}")
            run = 0
        out.append(s[i])
        run = run + 1 if s[i].isalnum() else 0
        i += 1
    return "".join(out)


def code_tokens(s: str) -> list[str]:
    """Split escaped code text into macros, separators and single characters."""
    toks: list[str] = []
    i = 0
    n = len(s)
    while i < n:
        if s[i] == "{":
            j = s.find("}", i)
            toks.append(s[i:j + 1] if j > 0 else s[i:])
            i = j + 1 if j > 0 else n
            continue
        if s[i] == "\\" and i + 1 < n and s[i + 1].isalpha():
            j = i + 1
            while j < n and s[j].isalpha():
                j += 1
            toks.append(s[i:j])
            i = j
            continue
        toks.append(s[i])
        i += 1
    return toks


MATH_IN_CODE_RE = re.compile(r"\$([^$]+)\$")

_MATH_SENTINEL = "\x01MATH{}\x01"


def escape_code(body: str) -> str:
    """Escape a raw Markdown code span for use inside `\\code{}`.

    `$...$` inside a code span means mathematics (`` `batch 1 $\\times$ accum 4` ``),
    not literal dollars, so those spans are lifted out first and spliced back
    afterwards as real inline math.

    Order matters for the rest: braces and backslash are escaped before the
    other specials, because escaping backslashes emits `\\textbackslash{}` and
    a later brace pass would escape the braces of that macro.
    """
    maths: list[str] = []

    def stash(m: re.Match) -> str:
        maths.append(norm_math(m.group(1)))
        return _MATH_SENTINEL.format(len(maths) - 1)

    body = MATH_IN_CODE_RE.sub(stash, body)

    body = body.replace("{", r"\{").replace("}", r"\}")
    body = body.replace("\\", r"\textbackslash{}")
    body = body.replace("_", r"\_").replace("%", r"\%")
    body = body.replace("#", r"\#").replace("&", r"\&")

    for i, math in enumerate(maths):
        body = body.replace(_MATH_SENTINEL.format(i), "$" + math + "$")
    return body


def code_segments(span: str) -> list[str]:
    """Split a raw code span the way `add_breaks` will.

    Used only to estimate widths, so it mirrors the break points `add_breaks`
    introduces: before each `/`, `_`, `.` and `-`, and every
    `CODE_BREAK_RUN` characters inside a separator-free run.
    """
    parts = [p for p in re.split(r"(?=[._\-/])", span) if p]
    if not COMPACT_TABLES:
        return parts
    out: list[str] = []
    for part in parts:
        while len(part) > CODE_BREAK_RUN:
            out.append(part[:CODE_BREAK_RUN])
            part = part[CODE_BREAK_RUN:]
        out.append(part)
    return out


def esc_text(s: str) -> str:
    """Escape LaTeX specials, then apply the Unicode text substitutions.

    Existing control sequences are preserved, so a heading map may inject
    markup such as `\\code{...}` without it being escaped into oblivion.
    """
    out: list[str] = []
    i = 0
    n = len(s)
    while i < n:
        ch = s[i]
        if ch == "\\" and i + 1 < n and (s[i + 1].isalpha() or s[i + 1] in "_%"):
            # pass a control sequence through untouched
            j = i + 1
            if s[j].isalpha():
                while j < n and s[j].isalpha():
                    j += 1
            else:
                j += 1
            out.append(s[i:j])
            i = j
            continue
        if ch in TEX_SPECIAL:
            # `eval_loss` written as plain text has no break opportunity at all,
            # so in a narrow table column it is an Overfull hbox.  With the
            # table-fitting fixes on, every escaped special becomes a break
            # point; `\allowbreak` only permits a break, so prose is unaffected.
            if COMPACT_TABLES and ch in "_%/":
                out.append(r"\allowbreak{}")
            out.append(TEX_SPECIAL[ch])
        elif ch in UNICODE_TEXT:
            out.append(UNICODE_TEXT[ch])
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def norm_math(s: str) -> str:
    """Normalise a math fragment: Unicode -> TeX, no text escaping.

    The source already contains LaTeX escapes such as `6\\%` inside `$...$`
    (a plain `%` would comment out the rest of the line), so pre-escaped
    specials must be preserved rather than escaped a second time.
    """
    for k, v in UNICODE_MATH.items():
        s = s.replace(k, " " + v + " ")
    for ch in ("\\",):
        s = s.replace(ch + "%", "\x00PCT\x00")
        s = s.replace(ch + "&", "\x00AMP\x00")
        s = s.replace(ch + "#", "\x00HASH\x00")
    s = s.replace("%", r"\%").replace("&", r"\&").replace("#", r"\#")
    s = s.replace("\x00PCT\x00", r"\%")
    s = s.replace("\x00AMP\x00", r"\&")
    s = s.replace("\x00HASH\x00", r"\#")
    s = re.sub(r"[ \t]{2,}", " ", s)
    return s.strip()


# token scanner for inline markup
_TOKEN_RE = re.compile(
    r"(?P<code>`[^`]+`)"
    r"|(?P<math>\$[^$\n]+\$)"
    r"|(?P<link>\[[^\]]+\]\([^)]+\))"
    r"|(?P<bold>\*\*[^*]+\*\*)"
    r"|(?P<strike>~~[^~]+~~)"
)


def inline(s: str, labels: dict[str, str] | None = None) -> str:
    """Convert one line of Markdown inline markup to LaTeX."""
    labels = labels or {}
    out: list[str] = []
    pos = 0
    for m in _TOKEN_RE.finditer(s):
        out.append(esc_text(s[pos:m.start()]))
        kind = m.lastgroup
        tok = m.group(0)
        if kind == "code":
            body = escape_code(tok[1:-1])
            # `add_breaks` is normally limited to long spans; a report that asks
            # for long-run breaks gets them in every span, because a short span
            # inside a narrow table column is just as unbreakable as a long one
            if len(body) > 18 or COMPACT_TABLES:
                body = add_breaks(body)
            out.append(r"\code{" + body + "}")
        elif kind == "math":
            out.append("$" + norm_math(tok[1:-1]) + "$")
        elif kind == "link":
            mm = re.match(r"\[([^\]]+)\]\(([^)]+)\)", tok)
            text, href = mm.group(1), mm.group(2)
            if href.startswith("#"):
                key = href.lstrip("#")
                if key in labels:
                    out.append(r"\hyperref[" + labels[key] + "]{" + esc_text(text) + "}")
                else:
                    out.append(r"\textbf{" + esc_text(text) + "}")
            else:
                out.append(r"\href{" + href + "}{" + esc_text(text) + "}")
        elif kind == "bold":
            out.append(r"\textbf{" + inline(tok[2:-2], labels) + "}")
        elif kind == "strike":
            out.append(r"\sout{" + inline(tok[2:-2], labels) + "}")
        pos = m.end()
    out.append(esc_text(s[pos:]))
    return "".join(out)


