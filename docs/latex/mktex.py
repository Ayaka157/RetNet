SUPP_CODE_RE = re.compile(r"\\code\{([^{}]*)\}")


def breakable_supplement_code(text: str, limit: int = 12) -> str:
    """Give long `\\code{}` spans in a hand-written supplement break points.

    The supplement is raw LaTeX, so its code spans never went through
    `add_breaks`: a 64-character sha256 or a long log path inside a narrow table
    column is then an Overfull hbox by construction.  Every span longer than
    `limit` characters is cut at its `/`, `.` and `\\_` separators (or every
    `limit` characters when it has none), and the pieces are rejoined with
    `\\linebreak[0]`, which only *permits* a break.
    """
    def repl(m: re.Match) -> str:
        body = m.group(1)
        if len(body) <= limit:
            return m.group(0)
        pieces: list[str] = []
        cur = ""
        for part in re.split(r"(?=[/.]|\\_)", body):
            while len(part) > limit:
                if cur:
                    pieces.append(cur)
                    cur = ""
                pieces.append(part[:limit])
                part = part[limit:]
            if len(cur) + len(part) > limit:
                pieces.append(cur)
                cur = part
            else:
                cur += part
        if cur:
            pieces.append(cur)
        return r"\linebreak[0]".join(
            r"\code{" + p + "}" for p in pieces if p)

    return SUPP_CODE_RE.sub(repl, text)


