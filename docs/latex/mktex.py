def merge_supplement(path: Path) -> str:
    """Return a hand-written English supplement body.

    The 272M supplement was authored in fragments and then consolidated by its
    author into `en/_supplement.tex`, which is now the complete English prose
    for Architecture (§3) through the appendices.  The per-part fragments are
    kept only as history and are deliberately *not* concatenated, because they
    overlap.  Any leftover part anchor is stripped.
    """
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"^%<<PART\d+>>\s*$", "", text, flags=re.M)
    return text.rstrip() + "\n"


