"""
mktex.py -- convert a Markdown technical report into XeLaTeX sources.

Two reports are configured (see `REPORTS`):

  * RetNet-272M -- `docs/19_RetNet-272M_技术报告.md` is a *bilingual single
    file*: every top-level section carries a `### N.N 中文` and a
    `### N.N English` half.  The Chinese edition keeps the Chinese halves, the
    English edition keeps the source's own English Introduction and takes the
    rest of its prose from the hand-written `en/_supplement.tex`.

  * RetNet-0.5B -- `docs/26_RetNet-0.5B_技术报告.md` is *Chinese-only*, with no
    paired English markers.  The Chinese edition is therefore the Markdown body
    as it stands, and the whole English edition is supplied by the hand-written
    `reports/0p5b/en_supplement.tex` (the same role `en/_supplement.tex` plays
    for 272M).

Every report is described by a `Report` record, so adding a third report means
adding a record plus its hand-written preamble / title / supplement fragments --
not touching the build logic.  Output is deterministic: re-running regenerates
byte-identical .tex unless the Markdown source or this script changes.

Usage:
    python mktex.py                 # every report whose source exists
    python mktex.py --report 0p5b   # only that report (fails if it is absent)
    python mktex.py --list
"""

